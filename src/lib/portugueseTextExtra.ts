function shouldSkip(el: Element | null) {
  if (!el) return true;
  const tag = el.tagName.toLowerCase();
  return tag === "script" || tag === "style" || tag === "noscript" || !!el.closest("[data-no-translate]");
}

function translateText(node: Text) {
  if (shouldSkip(node.parentElement)) return;
  const original = node.nodeValue || "";
  const trimmed = original.trim();
  if (!trimmed) return;

  const exact = EXTRA_TRANSLATIONS[trimmed];
  if (exact) {
    node.nodeValue = original.replace(trimmed, exact);
    return;
  }

  let result = original;
  for (const [from, to] of Object.entries(EXTRA_TRANSLATIONS)) {
    if (result.includes(from)) result = result.split(from).join(to);
  }
  if (result !== original) node.nodeValue = result;
}

function walk(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  nodes.forEach(translateText);
}

export function installExtraPortugueseTranslations() {
  if (typeof window === "undefined") return;
  const run = () => document.body && walk(document.body);
  run();
  window.addEventListener("DOMContentLoaded", run, { once: true });

  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) translateText(node as Text);
        if (node.nodeType === Node.ELEMENT_NODE) walk(node as Element);
      });
    });
  });

  const start = () => document.body && observer.observe(document.body, { childList: true, subtree: true });
  start();
  window.addEventListener("DOMContentLoaded", start, { once: true });
}
